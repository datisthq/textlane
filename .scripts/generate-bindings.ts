import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join, relative, resolve } from "node:path"
import { parseArgs } from "node:util"

// Writes each domain's module for both bindings from the crate's plugin list and option
// schemas (`cargo run --example schema`): the TypeScript one under typescript/generated/, the
// Python one under python/textlane/. `--check` writes nothing and fails on drift.

interface Schema {
  type?: string | string[]
  description?: string
  default?: unknown
  $ref?: string
  anyOf?: Schema[]
  oneOf?: Schema[]
  enum?: unknown[]
  const?: unknown
  items?: Schema
  properties?: Record<string, Schema>
  required?: string[]
  additionalProperties?: Schema | boolean
}

interface Domain {
  plugins: { name: string; options: Schema | null }[]
  $defs: Record<string, Schema>
}

const ROOT = resolve(import.meta.dirname, "..")
const HEADER =
  "Generated by `pnpm generate:bindings` from the crate's plugins; do not edit."

const { values } = parseArgs({ options: { check: { type: "boolean" } } })

const output = execFileSync(
  "cargo",
  ["run", "-q", "-p", "textlane", "--example", "schema", "--features", "schema"],
  { cwd: join(ROOT, "rust"), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
)
const domains: Record<string, Domain> = JSON.parse(output)

const files = new Map<string, string>()
for (const [name, domain] of Object.entries(domains)) {
  files.set(
    join(ROOT, "typescript", "generated", `${name}.ts`),
    writeTypescript(name, domain),
  )
  files.set(join(ROOT, "python", "textlane", `${name}.py`), writePython(name, domain))
}

const drifted: string[] = []
for (const [path, text] of files) {
  let current = ""
  try {
    current = readFileSync(path, "utf8")
  } catch {}
  if (current === text) continue
  drifted.push(relative(ROOT, path))
  if (!values.check) writeFileSync(path, text)
}
if (values.check && drifted.length > 0) {
  console.error(`out of date, run \`pnpm generate:bindings\`:\n  ${drifted.join("\n  ")}`)
  process.exit(1)
}
console.log(values.check ? "bindings up to date" : `wrote ${drifted.length} file(s)`)

function writeTypescript(domain: string, described: Domain) {
  const lines = [
    `// ${HEADER}`,
    "",
    'import type { Plugin } from "../models/plugin.ts"',
    "",
  ]
  for (const [name, schema] of Object.entries(described.$defs)) {
    lines.push(...writeDoc(schema.description, ""))
    if (schema.properties && !schema.anyOf) {
      lines.push(`export interface ${name} {`)
      for (const [key, property] of Object.entries(schema.properties)) {
        lines.push(...writeDoc(property.description, "  ", property.default))
        const optional = schema.required?.includes(key) ? "" : "?"
        lines.push(`  ${key}${optional}: ${writeType(property)}`)
      }
      lines.push("}", "")
    } else lines.push(`export type ${name} = ${writeType(schema)}`, "")
  }
  for (const plugin of described.plugins) {
    const name = plugin.name.slice(domain.length + 1)
    const options = plugin.options && readRef(plugin.options)
    lines.push(`/** The \`${plugin.name}\` plugin. */`)
    if (!options) {
      lines.push(
        `export function ${name}(): Plugin<"${plugin.name}"> {`,
        `  return { name: "${plugin.name}" }`,
        "}",
        "",
      )
      continue
    }
    lines.push(
      `export function ${name}(options?: ${options}): Plugin<"${plugin.name}", ${options}> {`,
      `  if (options === undefined) return { name: "${plugin.name}" }`,
      `  return { name: "${plugin.name}", options }`,
      "}",
      "",
    )
  }
  return `${lines.join("\n").trimEnd()}\n`
}

function writeType(schema: Schema | boolean): string {
  if (typeof schema === "boolean") return "unknown"
  if (schema.$ref) return readRef(schema)
  const union = schema.anyOf ?? schema.oneOf
  if (union) return joinUnion(union.map(writeType))
  if (schema.enum) return joinUnion(schema.enum.map(value => JSON.stringify(value)))
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (Array.isArray(schema.type)) {
    return joinUnion(schema.type.map(type => writeType({ ...schema, type })))
  }
  switch (schema.type) {
    case "string":
      return "string"
    case "boolean":
      return "boolean"
    case "number":
    case "integer":
      return "number"
    case "null":
      return "null"
    case "array": {
      const item = schema.items ? writeType(schema.items) : "unknown"
      return item.includes(" ") ? `(${item})[]` : `${item}[]`
    }
    case "object": {
      if (schema.properties) {
        const fields = Object.entries(schema.properties).map(([key, property]) => {
          const optional = schema.required?.includes(key) ? "" : "?"
          return `${key}${optional}: ${writeType(property)}`
        })
        return `{ ${fields.join("; ")} }`
      }
      const value = schema.additionalProperties
      return `Record<string, ${value === undefined ? "unknown" : writeType(value)}>`
    }
  }
  return "unknown"
}

function writeDoc(description: string | undefined, indent: string, value?: unknown) {
  const text = (description ?? "").split("\n").join(" ").trim()
  const fallback =
    value === undefined || value === null ? [] : [`@default ${JSON.stringify(value)}`]
  const parts = [text, ...fallback].filter(Boolean)
  if (parts.length === 0) return []
  return [`${indent}/** ${parts.join(" ")} */`]
}

function writePython(domain: string, described: Domain) {
  const definitions: string[] = []
  const written = new Set<string>()
  const writeDefinition = (name: string, schema: Schema) => {
    if (written.has(name)) return
    written.add(name)
    for (const dependency of listRefs(schema)) {
      const target = described.$defs[dependency]
      if (target) writeDefinition(dependency, target)
    }
    if (schema.properties && !schema.anyOf) {
      definitions.push(...writeTypedDict(name, schema, definitions))
    } else {
      const comment = writePythonComment(schema.description, "")
      definitions.push(
        ...comment,
        `${name} = ${writePythonType(schema, name, definitions)}`,
        "",
      )
    }
  }
  for (const [name, schema] of Object.entries(described.$defs))
    writeDefinition(name, schema)

  const functions: string[] = []
  const exported: string[] = []
  for (const plugin of described.plugins) {
    const name = toSnakeCase(plugin.name.slice(domain.length + 1))
    const options = plugin.options && readRef(plugin.options)
    exported.push(name)
    if (!options) {
      functions.push(
        `def ${name}() -> Plugin:`,
        `    """The \`${plugin.name}\` plugin."""`,
        `    return describe_plugin("${plugin.name}")`,
        "",
        "",
      )
      continue
    }
    exported.push(options)
    functions.push(
      `def ${name}(options: Optional[${options}] = None) -> Plugin:`,
      `    """The \`${plugin.name}\` plugin."""`,
      `    return describe_plugin("${plugin.name}", options)`,
      "",
      "",
    )
  }
  const lines = [
    `# ${HEADER}`,
    `"""The ${domain} plugins: each returns the descriptor \`Processor.use\` takes."""`,
    "",
    "from typing import Any, Dict, List, Literal, Optional, TypedDict, Union",
    "",
    "from ._models import Plugin, describe_plugin",
    "",
    "__all__ = [",
    ...[...new Set(exported)].map(name => `    "${name}",`),
    "]",
    "",
    "",
    ...definitions.flatMap(line => (line === "" ? ["", ""] : [line])),
    ...functions,
  ]
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n\n")
    .trimEnd()}\n`
}

// A TypedDict is total=False, with required keys in a base of their own: Python 3.9 has
// no `Required`
function writeTypedDict(name: string, schema: Schema, definitions: string[]): string[] {
  const properties = Object.entries(schema.properties ?? {})
  const required = properties.filter(([key]) => schema.required?.includes(key))
  const optional = properties.filter(([key]) => !schema.required?.includes(key))
  const field = ([key, property]: [string, Schema]) => [
    ...writePythonComment(property.description, "    "),
    `    ${key}: ${writePythonType(property, name + toPascalCase(key), definitions)}`,
  ]
  const lines: string[] = []
  let base = "TypedDict"
  if (required.length > 0) {
    base = `_${name}Required`
    lines.push(`class ${base}(TypedDict):`, ...required.flatMap(field), "")
  }
  lines.push(...writePythonComment(schema.description, ""))
  lines.push(`class ${name}(${base}, total=False):`)
  lines.push(...(optional.length > 0 ? optional.flatMap(field) : ["    pass"]), "")
  return lines
}

function writePythonType(
  schema: Schema | boolean,
  name: string,
  definitions: string[],
): string {
  if (typeof schema === "boolean") return "Any"
  if (schema.$ref) return readRef(schema)
  const union = schema.anyOf ?? schema.oneOf
  if (union) {
    return joinPythonUnion(
      union.map((item, index) => writePythonType(item, `${name}${index}`, definitions)),
    )
  }
  if (schema.enum)
    return `Literal[${schema.enum.map(value => JSON.stringify(value)).join(", ")}]`
  if (schema.const !== undefined) return `Literal[${JSON.stringify(schema.const)}]`
  if (Array.isArray(schema.type)) {
    return joinPythonUnion(
      schema.type.map(type => writePythonType({ ...schema, type }, name, definitions)),
    )
  }
  switch (schema.type) {
    case "string":
      return "str"
    case "boolean":
      return "bool"
    case "integer":
      return "int"
    case "number":
      return "float"
    case "null":
      return "None"
    case "array":
      return `List[${schema.items ? writePythonType(schema.items, name, definitions) : "Any"}]`
    case "object": {
      if (schema.properties) {
        definitions.push(
          ...writeTypedDict(name, { ...schema, description: undefined }, definitions),
        )
        return name
      }
      const value = schema.additionalProperties
      const item =
        value === undefined ? "Any" : writePythonType(value, `${name}Value`, definitions)
      return `Dict[str, ${item}]`
    }
  }
  return "Any"
}

function writePythonComment(description: string | undefined, indent: string) {
  if (!description) return []
  return description.split("\n").map(line => `${indent}# ${line}`.trimEnd())
}

function listRefs(schema: Schema | boolean): string[] {
  if (typeof schema === "boolean") return []
  const nested = [
    ...(schema.anyOf ?? []),
    ...(schema.oneOf ?? []),
    ...Object.values(schema.properties ?? {}),
    ...(schema.items ? [schema.items] : []),
    ...(typeof schema.additionalProperties === "object"
      ? [schema.additionalProperties]
      : []),
  ]
  return [...(schema.$ref ? [readRef(schema)] : []), ...nested.flatMap(listRefs)]
}

function readRef(schema: Schema) {
  return (schema.$ref ?? "").replace("#/$defs/", "")
}

function joinUnion(types: string[]) {
  return [...new Set(types)].join(" | ")
}

function joinPythonUnion(types: string[]) {
  const unique = [...new Set(types)]
  if (unique.length === 1) return unique[0] ?? "Any"
  const rest = unique.filter(type => type !== "None")
  if (rest.length === 1 && unique.includes("None")) return `Optional[${rest[0]}]`
  return `Union[${unique.join(", ")}]`
}

function toSnakeCase(name: string) {
  return name.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)
}

function toPascalCase(name: string) {
  return name.charAt(0).toUpperCase() + name.slice(1)
}
