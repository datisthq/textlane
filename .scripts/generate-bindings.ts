import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join, relative, resolve } from "node:path"
import { parseArgs } from "node:util"
import {
  listRefs,
  readRef,
  renderOptions,
  replaceSections,
  toSnakeCase,
  writePythonComment,
  writePythonType,
  writeType,
  writeTypedDict,
} from "./render-options.ts"
import type { DescribedPlugin, Language, Schema } from "./render-options.ts"

// Writes each domain's module for both bindings from the crate's plugin list and option
// schemas (`cargo run --example schema`): the TypeScript one under typescript/generated/, the
// Python one under python/textlane/, and each plugin's options into the docs pages
// `<language>/docs/plugins-<domain>.md`. `--check` writes nothing and fails on drift.

interface Domain {
  plugins: DescribedPlugin[]
  $defs: Record<string, Schema>
}

const ROOT = resolve(import.meta.dirname, "..")
const HEADER =
  "Generated by `pnpm generate:bindings` from the crate's plugins; do not edit."

const { values } = parseArgs({ options: { check: { type: "boolean" } } })

const output = execFileSync(
  "cargo",
  ["run", "-q", "-p", "textlane", "--example", "schema", "--features", "schema"],
  { cwd: join(ROOT, "rust"), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
)
const domains: Record<string, Domain> = JSON.parse(output)

const files = new Map<string, string>()
for (const [name, domain] of Object.entries(domains)) {
  files.set(
    join(ROOT, "typescript", "generated", `${name}.ts`),
    writeTypescript(name, domain),
  )
  files.set(join(ROOT, "python", "textlane", `${name}.py`), writePython(name, domain))
}

const LANGUAGES: Record<Language, string> = {
  typescript: "typescript/docs",
  python: "python/docs",
  rust: "rust/docs",
}
const unwritten: string[] = []
for (const [language, directory] of Object.entries(LANGUAGES) as [Language, string][]) {
  for (const [name, domain] of Object.entries(domains)) {
    const path = join(ROOT, directory, `plugins-${name}.md`)
    let text = ""
    try {
      text = readFileSync(path, "utf8")
    } catch {}
    const plugins = new Map(domain.plugins.map(plugin => [plugin.name, plugin]))
    const result = replaceSections({
      text,
      names: [...plugins.keys()],
      render: plugin => {
        const described = plugins.get(plugin)
        if (!described) return ""
        return renderOptions({ language, plugin: described, definitions: domain.$defs })
      },
    })
    for (const plugin of result.missing)
      unwritten.push(`${directory}: no ${plugin} section`)
    for (const plugin of result.unknown)
      unwritten.push(`${directory}: no ${plugin} plugin`)
    if (text) files.set(path, result.text)
  }
}
if (unwritten.length > 0) {
  console.error(
    `docs sections out of step with the plugins:\n  ${unwritten.join("\n  ")}`,
  )
  process.exit(1)
}

const drifted: string[] = []
for (const [path, text] of files) {
  let current = ""
  try {
    current = readFileSync(path, "utf8")
  } catch {}
  if (current === text) continue
  drifted.push(relative(ROOT, path))
  if (!values.check) writeFileSync(path, text)
}
if (values.check && drifted.length > 0) {
  console.error(`out of date, run \`pnpm generate:bindings\`:\n  ${drifted.join("\n  ")}`)
  process.exit(1)
}
console.log(values.check ? "bindings up to date" : `wrote ${drifted.length} file(s)`)

function writeTypescript(domain: string, described: Domain) {
  const lines = [
    `// ${HEADER}`,
    "",
    'import type { Plugin } from "../models/plugin.ts"',
    "",
  ]
  for (const [name, schema] of Object.entries(described.$defs)) {
    lines.push(...writeDoc(schema.description, ""))
    if (schema.properties && !schema.anyOf) {
      lines.push(`export interface ${name} {`)
      for (const [key, property] of Object.entries(schema.properties)) {
        lines.push(...writeDoc(property.description, "  ", property.default))
        const optional = schema.required?.includes(key) ? "" : "?"
        lines.push(`  ${key}${optional}: ${writeType(property)}`)
      }
      lines.push("}", "")
    } else lines.push(`export type ${name} = ${writeType(schema)}`, "")
  }
  for (const plugin of described.plugins) {
    const name = plugin.name.slice(domain.length + 1)
    const options = plugin.options && readRef(plugin.options)
    lines.push(`/** The \`${plugin.name}\` plugin. */`)
    if (!options) {
      lines.push(
        `export function ${name}(): Plugin<"${plugin.name}"> {`,
        `  return { name: "${plugin.name}" }`,
        "}",
        "",
      )
      continue
    }
    lines.push(
      `export function ${name}(options?: ${options}): Plugin<"${plugin.name}", ${options}> {`,
      `  if (options === undefined) return { name: "${plugin.name}" }`,
      `  return { name: "${plugin.name}", options }`,
      "}",
      "",
    )
  }
  return `${lines.join("\n").trimEnd()}\n`
}

function writeDoc(description: string | undefined, indent: string, value?: unknown) {
  const text = (description ?? "").split("\n").join(" ").trim()
  const fallback =
    value === undefined || value === null ? [] : [`@default ${JSON.stringify(value)}`]
  const parts = [text, ...fallback].filter(Boolean)
  if (parts.length === 0) return []
  return [`${indent}/** ${parts.join(" ")} */`]
}

function writePython(domain: string, described: Domain) {
  const definitions: string[] = []
  const written = new Set<string>()
  const writeDefinition = (name: string, schema: Schema) => {
    if (written.has(name)) return
    written.add(name)
    for (const dependency of listRefs(schema)) {
      const target = described.$defs[dependency]
      if (target) writeDefinition(dependency, target)
    }
    if (schema.properties && !schema.anyOf) {
      definitions.push(...writeTypedDict(name, schema, definitions))
    } else {
      const comment = writePythonComment(schema.description, "")
      definitions.push(
        ...comment,
        `${name} = ${writePythonType(schema, name, definitions)}`,
        "",
      )
    }
  }
  for (const [name, schema] of Object.entries(described.$defs))
    writeDefinition(name, schema)

  const functions: string[] = []
  const exported: string[] = []
  for (const plugin of described.plugins) {
    const name = toSnakeCase(plugin.name.slice(domain.length + 1))
    const options = plugin.options && readRef(plugin.options)
    exported.push(name)
    if (!options) {
      functions.push(
        `def ${name}() -> Plugin:`,
        `    """The \`${plugin.name}\` plugin."""`,
        `    return describe_plugin("${plugin.name}")`,
        "",
        "",
      )
      continue
    }
    exported.push(options)
    functions.push(
      `def ${name}(options: Optional[${options}] = None) -> Plugin:`,
      `    """The \`${plugin.name}\` plugin."""`,
      `    return describe_plugin("${plugin.name}", options)`,
      "",
      "",
    )
  }
  const lines = [
    `# ${HEADER}`,
    `"""The ${domain} plugins: each returns the descriptor \`Processor.use\` takes."""`,
    "",
    "from typing import Any, Dict, List, Literal, Optional, TypedDict, Union",
    "",
    "from ._models import Plugin, describe_plugin",
    "",
    "__all__ = [",
    ...[...new Set(exported)].map(name => `    "${name}",`),
    "]",
    "",
    "",
    ...definitions.flatMap(line => (line === "" ? ["", ""] : [line])),
    ...functions,
  ]
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n\n")
    .trimEnd()}\n`
}
