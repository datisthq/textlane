import { writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { bundledThemes, normalizeTheme } from "shiki"

// The theme data `html.highlight` reads beside giallo's parsed themes, generated from the
// themes the pinned Shiki bundles, so the Rust table never drifts from what it ships
const HELPERS = resolve(import.meta.dirname, "..", "..", "rust", "html", "src", "helpers")
const ANSI_NAMES = [
  "Black",
  "Red",
  "Green",
  "Yellow",
  "Blue",
  "Magenta",
  "Cyan",
  "White",
  "BrightBlack",
  "BrightRed",
  "BrightGreen",
  "BrightYellow",
  "BrightBlue",
  "BrightMagenta",
  "BrightCyan",
  "BrightWhite",
]

const names = Object.keys(bundledThemes).sort() as (keyof typeof bundledThemes)[]
const rows = []
for (const name of names) {
  const theme = normalizeTheme((await bundledThemes[name]()).default)
  const terminal = ANSI_NAMES.map(color => theme.colors?.[`terminal.ansi${color}`])
  rows.push(
    [
      "    ThemeColors {",
      `        name: ${quote(name)},`,
      `        fg: ${quote(theme.fg)},`,
      `        bg: ${quote(theme.bg)},`,
      `        spellings: &[${findSpellings(theme)
        .map(([written, spelled]) => `(${quote(written)}, ${quote(spelled)})`)
        .join(", ")}],`,
      `        terminal: [${terminal.map(color => (color ? `Some(${quote(color)})` : "None")).join(", ")}],`,
      "    },",
    ].join("\n"),
  )
}
writeFileSync(
  join(HELPERS, "theme_table.rs"),
  [
    `// Shiki 4.5.0's bundled themes, normalized as it normalizes them: each one's name, its`,
    "// `fg` and `bg` as written, and the token colors whose spelling giallo's parsed color loses;",
    "// generated by `pnpm -C conformance generate:highlight-tables`, never edited by hand",
    `pub(crate) static THEMES: [ThemeColors; ${rows.length}] = [`,
    ...rows,
    "];",
    "",
    "pub(crate) struct ThemeColors {",
    "    pub(crate) name: &'static str,",
    "    pub(crate) fg: &'static str,",
    "    pub(crate) bg: &'static str,",
    "    // Each color as giallo writes it, then as the theme spells it, uppercased",
    "    pub(crate) spellings: &'static [(&'static str, &'static str)],",
    "    // `terminal.ansi*` as written, black to bright white, which color `ansi` code",
    "    pub(crate) terminal: [Option<&'static str>; 16],",
    "}",
    "",
  ].join("\n"),
)

// vscode-textmate uppercases each token color and giallo parses it to `#RRGGBB[AA]`; the
// theme's own `fg`, when written as giallo writes it, keeps that spelling for every token
function findSpellings(theme: {
  fg: string
  settings: { settings?: { foreground?: string } }[]
}) {
  const spellings: [string, string][] = []
  for (const setting of theme.settings) {
    const color = setting.settings?.foreground
    if (typeof color !== "string") continue
    const spelled = color.toUpperCase()
    const written = parseHex(spelled)
    if (!written || written === spelled || written === theme.fg.toUpperCase()) continue
    if (!spellings.some(([known]) => known === written))
      spellings.push([written, spelled])
  }
  return spellings
}

function parseHex(color: string) {
  const digits = color.slice(1)
  if (!/^[0-9A-F]+$/.test(digits)) return undefined
  const long =
    digits.length === 3 || digits.length === 4
      ? [...digits].map(digit => digit + digit).join("")
      : digits
  if (long.length !== 6 && long.length !== 8) return undefined
  return `#${long.length === 8 && long.endsWith("FF") ? long.slice(0, 6) : long}`
}

function quote(value: string) {
  return JSON.stringify(value)
}
