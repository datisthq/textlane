import { writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { emoticon } from "emoticon"

// The data tables `textlane-md`'s plugins read, generated from the pinned packages, so the
// Rust tables never drift from what upstream ships
const GEMOJI = resolve(
  import.meta.dirname,
  "..",
  "..",
  "rust",
  "md",
  "src",
  "plugins",
  "gemoji",
)

writeEmoticons()

// remark-emoji finds an emoticon's entry with `emoticon.find(e => e.emoticons.includes(x))`:
// the first entry listing it wins, so each emoticon keeps only that one
function writeEmoticons() {
  const first = new Map<string, { name: string; emoji: string }>()
  for (const entry of emoticon)
    for (const text of entry.emoticons)
      if (!first.has(text)) first.set(text, { name: entry.name, emoji: entry.emoji })
  const rows = [...first]
    // Rust compares `&str` by UTF-8 bytes, which JavaScript's `<` on UTF-16 units does not
    .sort(([left], [right]) => Buffer.compare(Buffer.from(left), Buffer.from(right)))
    .map(
      ([text, { name, emoji }]) =>
        `    (${quote(text)}, ${quote(name)}, ${quote(emoji)}),`,
    )
  writeFileSync(
    join(GEMOJI, "emoticons.rs"),
    [
      "// emoticon 4.1.0's emoticons, each with the first entry listing it, sorted for a",
      "// binary search; generated by `pnpm -C conformance generate:md-tables`",
      `pub(crate) static EMOTICONS: [(&str, &str, &str); ${rows.length}] = [`,
      ...rows,
      "];",
      "",
    ].join("\n"),
  )
  console.log(`emoticons: ${rows.length}`)
}

function quote(text: string) {
  let out = '"'
  for (const character of text) {
    const code = character.codePointAt(0) ?? 0
    if (character === '"' || character === "\\") out += `\\${character}`
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16).toUpperCase()}}`
    else out += character
  }
  return `${out}"`
}
