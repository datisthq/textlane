import { writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { emoticon } from "emoticon"
import { classifyCharacter } from "micromark-extension-cjk-friendly-util"

// The data tables `textlane-md`'s plugins read, generated from the pinned packages, so the
// Rust tables never drift from what upstream ships
const MD = resolve(import.meta.dirname, "..", "..", "rust", "md", "src")
const GEMOJI = join(MD, "plugins", "gemoji")

writeEmoticons()
writeCjkClasses()

// remark-emoji finds an emoticon's entry with `emoticon.find(e => e.emoticons.includes(x))`:
// the first entry listing it wins, so each emoticon keeps only that one
function writeEmoticons() {
  const first = new Map<string, { name: string; emoji: string }>()
  for (const entry of emoticon)
    for (const text of entry.emoticons)
      if (!first.has(text)) first.set(text, { name: entry.name, emoji: entry.emoji })
  const rows = [...first]
    // Rust compares `&str` by UTF-8 bytes, which JavaScript's `<` on UTF-16 units does not
    .sort(([left], [right]) => Buffer.compare(Buffer.from(left), Buffer.from(right)))
    .map(
      ([text, { name, emoji }]) =>
        `    (${quote(text)}, ${quote(name)}, ${quote(emoji)}),`,
    )
  writeFileSync(
    join(GEMOJI, "emoticons.rs"),
    [
      "// emoticon 4.1.0's emoticons, each with the first entry listing it, sorted for a",
      "// binary search; generated by `pnpm -C conformance generate:md-tables`",
      `pub(crate) static EMOTICONS: [(&str, &str, &str); ${rows.length}] = [`,
      ...rows,
      "];",
      "",
    ].join("\n"),
  )
  console.log(`emoticons: ${rows.length}`)
}

// micromark-extension-cjk-friendly-util's `classifyCharacter` for every code point, as
// ranges of one class: CJK, ideographic variation selectors, other variation selectors,
// Unicode white space and punctuation, by East Asian Width, Emoji_Presentation and script
function writeCjkClasses() {
  const rows: string[] = []
  const hex = (code: number) => `0x${code.toString(16).toUpperCase()}`
  let start = 0
  let current: number = classifyCharacter(0)
  for (let code = 1; code <= 0x110000; code++) {
    const kind = code <= 0x10ffff ? classifyCharacter(code) : -1
    if (kind === current) continue
    if (current !== 0) rows.push(`    (${hex(start)}, ${hex(code - 1)}, ${current}),`)
    start = code
    current = kind
  }
  writeFileSync(
    join(MD, "helpers", "cjk_table.rs"),
    [
      "// micromark-extension-cjk-friendly-util 3.0.1's `classifyCharacter` for every code point",
      "// that is not plain: `(first, last, class)`, sorted for a binary search; generated by",
      "// `pnpm -C conformance generate:md-tables`",
      `pub(crate) static CJK_CLASSES: [(u32, u32, u16); ${rows.length}] = [`,
      ...rows,
      "];",
      "",
    ].join("\n"),
  )
  console.log(`cjk classes: ${rows.length} ranges`)
}

function quote(text: string) {
  let out = '"'
  for (const character of text) {
    const code = character.codePointAt(0) ?? 0
    if (character === '"' || character === "\\") out += `\\${character}`
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16).toUpperCase()}}`
    else out += character
  }
  return `${out}"`
}
