// GFM spec categories and remark-gfm fixture prefixes onto construct files
const CATEGORY_CONSTRUCTS: Record<string, string> = {
  Tables: "gfm-table",
  "Task list items": "gfm-task-list-item",
  Strikethrough: "gfm-strikethrough",
  Autolinks: "gfm-autolink-literal",
}
const FIXTURE_CONSTRUCTS: [RegExp, string][] = [
  [/^table/, "gfm-table"],
  [/^strikethrough/, "gfm-strikethrough"],
  [/^tasklist/, "gfm-task-list-item"],
  [/^autolink/, "gfm-autolink-literal"],
]
// Extension arguments that are remark-gfm options under the same name
const GFM_OPTIONS = new Set([
  "singleTilde",
  "tableCellPadding",
  "tablePipeAlign",
  "firstLineBlank",
])

type Group = {
  description: string
  source: { repository: string; commit: string; path: string; license: string }
  pipeline: unknown[]
  tests: object[]
}

const GFM: MdastSyntax = {
  plugin: "md.gfm",
  extension: "gfm",
  isExtension: name => name.startsWith("gfm"),
  options: GFM_OPTIONS,
}

const skipped = new Map<string, number>()
let written = 0
importGfmMdast()

function importGfmMdast() {
  for (const repository of REPOSITORIES) {
    const root = fetchSource({ repository: repository.url, commit: repository.commit })
    const groups = new Map<string, Group>()
    const source = readFileSync(join(root, repository.test), "utf8")
    for (const found of extractMdastCases({ source, syntax: GFM, countSkip })) {
      const group = getGroup({
        groups,
        repository,
        path: repository.test,
        kind: found.kind,
        options: found.options,
      })
      group.tests.push(found.test)
      written += 1
    }
    writeGroups({
      path: join(OUTPUT, `${repository.construct}.json`),
      repository: repository.url,
      groups: [...groups.values()],
    })
  }
  importSpecRoundTrips()
  importRemarkGfmFixtures()
  console.log(`gfm-mdast: ${written} cases`)
  for (const [reason, count] of skipped) console.log(`  skipped ${count}: ${reason}`)
}

// mdast-util-gfm round-trips every GFM spec example; its snapshots are regenerated by the reference
function importSpecRoundTrips() {
  const root = fetchSource({ repository: GFM_UTIL.url, commit: GFM_UTIL.commit })
  const program = parse(readFileSync(join(root, "test", "spec.js"), "utf8"), {
    ecmaVersion: "latest",
    sourceType: "module",
  })
  let examples: unknown = []
  ancestor(program, {
    VariableDeclarator(node) {
      if (node.id.type === "Identifier" && node.id.name === "spec")
        examples = evaluateNode(node.init, new Map())
    },
  })
  const byConstruct = new Map<string, object[]>()
  for (const [index, example] of (Array.isArray(examples) ? examples : []).entries()) {
    if (!isObject(example) || !("category" in example) || !("input" in example)) continue
    const construct = CATEGORY_CONSTRUCTS[String(example.category)]
    if (!construct) {
      countSkip("GitHub's tag filter, in neither micromark nor unified")
      continue
    }
    const input = String(example.input)
    const md = stringifyTree({ tree: parseMarkdown(input, { gfm: {} }), gfm: {} })
    byConstruct.set(construct, [
      ...(byConstruct.get(construct) ?? []),
      { description: `example ${index + 1}`, input, expected: { md } },
    ])
    written += 1
  }
  for (const [construct, tests] of byConstruct) {
    const group = {
      description: "mdast-util-gfm spec round trip",
      source: {
        repository: GFM_UTIL.url,
        commit: GFM_UTIL.commit,
        path: "test/spec.js",
        license: "CC-BY-SA-4.0",
      },
      pipeline: [["md.parse"], ["md.gfm"], ["md.stringify"]],
      tests,
    }
    writeGroups({
      path: join(OUTPUT, `${construct}.json`),
      repository: GFM_UTIL.url,
      groups: [group],
    })
  }
}

// A fixture holds input.md, its tree.json and output.md, and remark-gfm options in config.json
function importRemarkGfmFixtures() {
  const root = join(
    fetchSource({ repository: REMARK_GFM.url, commit: REMARK_GFM.commit }),
    "test",
    "fixtures",
  )
  const byConstruct = new Map<string, Map<string, Group>>()
  for (const name of readdirSync(root).sort()) {
    const construct = FIXTURE_CONSTRUCTS.find(([pattern]) => pattern.test(name))?.[1]
    if (!construct) continue
    const configPath = join(root, name, "config.json")
    const gfm: Record<string, unknown> = existsSync(configPath)
      ? JSON.parse(readFileSync(configPath, "utf8"))
      : {}
    if ("stringLength" in gfm) {
      countSkip("a function-valued option (stringLength)")
      continue
    }
    const input = readFileSync(join(root, name, "input.md"), "utf8")
    const tree = parseMarkdown(input, { gfm: gfm })
    const md = stringifyTree({ tree, gfm })
    if (
      !isDeepStrictEqual(
        tree,
        JSON.parse(readFileSync(join(root, name, "tree.json"), "utf8")),
      )
    ) {
      console.log(`  remark-gfm fixture ${name} tree drifts from its snapshot`)
    }
    // No output.md means the output is the input, as remark-gfm's own test reads it
    const outputPath = join(root, name, "output.md")
    const snapshot = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : input
    const drift =
      md === snapshot
        ? {}
        : {
            comment: `remark-gfm's snapshot, from an older mdast-util-to-markdown: ${snapshot}`,
          }
    const groups = byConstruct.get(construct) ?? new Map<string, Group>()
    byConstruct.set(construct, groups)
    const options = Object.keys(gfm).length > 0 ? [["md.gfm", gfm]] : [["md.gfm"]]
    const suffix = Object.keys(gfm).length > 0 ? ` ${JSON.stringify(gfm)}` : ""
    const source = {
      repository: REMARK_GFM.url,
      commit: REMARK_GFM.commit,
      path: "test/fixtures",
      license: "MIT",
    }
    for (const [kind, pipeline, expected] of [
      ["tree", [["md.parse"], ...options], { tree }],
      ["output", [["md.parse"], ...options, ["md.stringify"]], { md }],
    ] as const) {
      const description = `remark-gfm fixtures (${kind})${suffix}`
      const group = groups.get(description) ?? {
        description,
        source,
        pipeline: [...pipeline],
        tests: [],
      }
      group.tests.push({
        description: `fixture ${name}`,
        ...(kind === "output" ? drift : {}),
        input,
        expected,
      })
      groups.set(description, group)
      written += 1
    }
  }
  for (const [construct, groups] of byConstruct) {
    writeGroups({
      path: join(OUTPUT, `${construct}.json`),
      repository: REMARK_GFM.url,
      groups: [...groups.values()],
    })
  }
}

function getGroup(props: {
  groups: Map<string, Group>
  repository: (typeof REPOSITORIES)[number]
  path: string
  kind: MdastKind
  options: MdastOptions
}) {
  const optionsSuffix = describeMdastOptions(props.options)
  const name = props.repository.url.split("/").pop() ?? props.repository.url
  const description = `${name} ${props.kind}${optionsSuffix}`
  const existing = props.groups.get(description)
  if (existing) return existing
  const group: Group = {
    description,
    source: {
      repository: props.repository.url,
      commit: props.repository.commit,
      path: props.path,
      license: "MIT",
    },
    pipeline: createMdastPipeline({
      syntax: GFM,
      kind: props.kind,
      options: props.options,
    }),
    tests: [],
  }
  props.groups.set(description, group)
  return group
}

function countSkip(reason: string) {
  skipped.set(reason, (skipped.get(reason) ?? 0) + 1)
  return undefined
}
