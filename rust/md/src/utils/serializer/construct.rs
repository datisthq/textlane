/// A construct the serializer is inside, which decides what `safe` escapes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Construct {
    Autolink,
    Blockquote,
    CodeFenced,
    CodeFencedLangGraveAccent,
    CodeFencedLangTilde,
    CodeFencedMetaGraveAccent,
    CodeFencedMetaTilde,
    CodeIndented,
    DefList,
    DefListDescription,
    DefListTerm,
    ContainerDirective,
    ContainerDirectiveLabel,
    Definition,
    DestinationLiteral,
    DestinationRaw,
    Emphasis,
    HeadingAtx,
    HeadingSetext,
    Image,
    ImageReference,
    Label,
    LeafDirective,
    LeafDirectiveLabel,
    Link,
    LinkReference,
    List,
    ListItem,
    MathFlow,
    MathFlowMeta,
    MdxJsxFlowElement,
    MdxJsxTextElement,
    Paragraph,
    Phrasing,
    Reference,
    Strikethrough,
    Strong,
    Table,
    TableCell,
    TableRow,
    TextDirective,
    TextDirectiveLabel,
    TitleApostrophe,
    TitleQuote,
}

impl Construct {
    pub(crate) const COUNT: usize = 44;

    /// The construct mdast-util-to-markdown calls `name`, if any.
    pub(crate) fn from_name(name: &str) -> Option<Construct> {
        Some(match name {
            "autolink" => Construct::Autolink,
            "blockquote" => Construct::Blockquote,
            "codeFenced" => Construct::CodeFenced,
            "codeFencedLangGraveAccent" => Construct::CodeFencedLangGraveAccent,
            "codeFencedLangTilde" => Construct::CodeFencedLangTilde,
            "codeFencedMetaGraveAccent" => Construct::CodeFencedMetaGraveAccent,
            "codeFencedMetaTilde" => Construct::CodeFencedMetaTilde,
            "codeIndented" => Construct::CodeIndented,
            "defList" => Construct::DefList,
            "defListDescription" => Construct::DefListDescription,
            "defListTerm" => Construct::DefListTerm,
            "containerDirective" => Construct::ContainerDirective,
            "containerDirectiveLabel" => Construct::ContainerDirectiveLabel,
            "definition" => Construct::Definition,
            "destinationLiteral" => Construct::DestinationLiteral,
            "destinationRaw" => Construct::DestinationRaw,
            "emphasis" => Construct::Emphasis,
            "headingAtx" => Construct::HeadingAtx,
            "headingSetext" => Construct::HeadingSetext,
            "image" => Construct::Image,
            "imageReference" => Construct::ImageReference,
            "label" => Construct::Label,
            "leafDirective" => Construct::LeafDirective,
            "leafDirectiveLabel" => Construct::LeafDirectiveLabel,
            "link" => Construct::Link,
            "linkReference" => Construct::LinkReference,
            "list" => Construct::List,
            "listItem" => Construct::ListItem,
            "mathFlow" => Construct::MathFlow,
            "mathFlowMeta" => Construct::MathFlowMeta,
            "mdxJsxFlowElement" => Construct::MdxJsxFlowElement,
            "mdxJsxTextElement" => Construct::MdxJsxTextElement,
            "paragraph" => Construct::Paragraph,
            "phrasing" => Construct::Phrasing,
            "reference" => Construct::Reference,
            "strikethrough" => Construct::Strikethrough,
            "strong" => Construct::Strong,
            "table" => Construct::Table,
            "tableCell" => Construct::TableCell,
            "tableRow" => Construct::TableRow,
            "textDirective" => Construct::TextDirective,
            "textDirectiveLabel" => Construct::TextDirectiveLabel,
            "titleApostrophe" => Construct::TitleApostrophe,
            "titleQuote" => Construct::TitleQuote,
            _ => return None,
        })
    }
}
