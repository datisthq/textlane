/// The id of a tag name, as parse5's `getTagID`: exact, so `foreignobject` is unknown.
pub(crate) fn find_tag_id(name: &str) -> TagId {
    TAG_IDS
        .binary_search_by(|(each, _)| each.cmp(&name))
        .map_or(TagId::Unknown, |index| TAG_IDS[index].1)
}
