// parse-latin's `abbreviationPrefix`, besides one to three digits or one letter
const LATIN_ABBREVIATIONS: [&str; 24] = [
    "al", "ca", "cap", "cca", "cent", "cf", "cit", "con", "cp", "cwt", "ead", "etc",
    "ff", "fl", "ibid", "id", "nem", "op", "pro", "seq", "sic", "stat", "tem", "viz",
];

/// Whether a lower-cased word is one parse-latin keeps a full stop in.
pub(crate) fn is_latin_abbreviation(value: &str) -> bool {
    let bytes = value.as_bytes();
    (matches!(bytes.len(), 1..=3) && bytes.iter().all(u8::is_ascii_digit))
        || (bytes.len() == 1 && bytes[0].is_ascii_lowercase())
        || LATIN_ABBREVIATIONS.binary_search(&value).is_ok()
}

/// Whether a word is one parse-english keeps a full stop in: `value` as written and
/// `lower` lower-cased.
pub(crate) fn is_english_abbreviation(value: &str, lower: &str) -> bool {
    ABBREVIATIONS.binary_search(&lower).is_ok()
        || ABBREVIATIONS_SENSITIVE.binary_search(&value).is_ok()
}

/// Whether a lower-cased word is `o` or `ol`, which an apostrophe after shortens (`ol'`).
pub(crate) fn is_elision_prefix(lower: &str) -> bool {
    matches!(lower, "o" | "ol")
}

/// Whether a lower-cased word is one an apostrophe before shortens (`'tis`, `'90s`).
pub(crate) fn is_elision_affix(lower: &str) -> bool {
    let bytes = lower.as_bytes();
    matches!(
        lower,
        "twere" | "twas" | "tis" | "cause" | "em" | "er" | "im"
    ) || (matches!(bytes.len(), 2 | 3)
        && bytes[0].is_ascii_digit()
        && bytes[1].is_ascii_digit()
        && bytes.get(2).is_none_or(|byte| *byte == b's'))
}
